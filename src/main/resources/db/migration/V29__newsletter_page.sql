ALTER TABLE newsletter
    ADD CONSTRAINT chk_newsletter_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'PAUSED', 'COMPLETED', 'FAILED'));

--  newsletter 문서 단위 페이지 메타데이터 + 멈춤 상태
--    source_type : PDF / IMAGE (기존 레코드는 NULL → 파일 확장자로 판단)
--    total_pages : 전체 페이지 수 (PDF는 클로바 OCR 응답 후 확정)
--    paused_*    : PAUSED 상태일 때 어느 페이지가 어떤 단계/사유로 멈췄는지
--    paused_at   : 24시간 방치 시 자동 FAILED 처리 기준 시각
ALTER TABLE newsletter
    ADD COLUMN IF NOT EXISTS source_type VARCHAR(10) NULL;

ALTER TABLE newsletter
    ADD COLUMN IF NOT EXISTS total_pages INTEGER NULL;

ALTER TABLE newsletter
